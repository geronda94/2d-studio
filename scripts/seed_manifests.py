def run():
    ensure_columns()

    db = SessionLocal()
    try:
        comps = db.query(models.Component).all()
        done = 0
        for c in comps:
            m = MANIFESTS.get(c.slug)
            if m:
                c.description = m["description"]
                c.manifest = m["manifest"] + MANIFEST_RULES
                done += 1
            else:
                print(f"WARN: нет манифеста для {c.slug}")

            # Обязательные поля (кураторские) — помечаем в payload_schema.
            # Идемпотентно: сначала снимаем ВСЕ устаревшие required (иначе поле,
            # убранное из REQUIRED_FIELDS, навсегда остаётся обязательным в БД),
            # затем ставим актуальные.
            required = REQUIRED_FIELDS.get(c.slug, [])
            if c.payload_schema:
                schema = copy.deepcopy(c.payload_schema)
                for field in schema.get("fields", {}).values():
                    if isinstance(field, dict):
                        field.pop("required", None)
                for field in required:
                    if field in schema.get("fields", {}):
                        schema["fields"][field]["required"] = True
                c.payload_schema = schema

        db.commit()
        print(f"description + manifest + required заполнены: {done}/{len(comps)} компонентов.")
    finally:
        db.close()




